#!/usr/bin/env node
/**
 * Build the PWA: static web export + a generated service worker that precaches
 * every exported file so the whole app (all 18 chapters, art, fonts) works offline.
 *
 *   npm run web:build          -> dist/
 *   npm run web:deploy         -> build + `eas deploy --prod`
 */
import { createHash } from 'node:crypto';
import { execFileSync } from 'node:child_process';
import { readdirSync, readFileSync, statSync, writeFileSync } from 'node:fs';
import { join, relative, sep } from 'node:path';

const root = new URL('..', import.meta.url).pathname;
const dist = join(root, 'dist');

execFileSync('npx', ['expo', 'export', '-p', 'web'], { cwd: root, stdio: 'inherit' });

function walk(dir, out = []) {
  for (const name of readdirSync(dir)) {
    const p = join(dir, name);
    if (statSync(p).isDirectory()) walk(p, out);
    else out.push(p);
  }
  return out;
}

const files = walk(dist)
  .map((p) => relative(dist, p).split(sep).join('/'))
  .filter((p) => !p.endsWith('.map') && p !== 'sw.js' && !p.startsWith('_expo/.routes'));

const urls = files.map((p) => '/' + p.split('/').map(encodeURIComponent).join('/'));
const hash = createHash('sha256');
for (const f of files) hash.update(f).update(readFileSync(join(dist, f)));
const version = hash.digest('hex').slice(0, 12);

const sw = `/* generated by scripts/build-web.mjs – do not edit */
const VERSION = ${JSON.stringify(version)};
const CACHE = 'gita-' + VERSION;
const PRECACHE = ${JSON.stringify(urls)};

self.addEventListener('install', (e) => {
  e.waitUntil(
    caches.open(CACHE).then((c) => c.addAll(PRECACHE)).then(() => self.skipWaiting()),
  );
});

self.addEventListener('activate', (e) => {
  e.waitUntil(
    caches
      .keys()
      .then((keys) =>
        Promise.all(keys.filter((k) => k.startsWith('gita-') && k !== CACHE).map((k) => caches.delete(k))),
      )
      .then(() => self.clients.claim()),
  );
});

async function navigationResponse(req, url) {
  const cache = await caches.open(CACHE);
  const path = url.pathname.replace(/\\/+$/, '');
  const candidates = [path || '/index.html', path + '.html', path + '/index.html', '/index.html'];
  for (const c of candidates) {
    const hit = await cache.match(c);
    if (hit) return hit;
  }
  try {
    return await fetch(req);
  } catch {
    return cache.match('/index.html');
  }
}

self.addEventListener('fetch', (e) => {
  const req = e.request;
  if (req.method !== 'GET') return;
  const url = new URL(req.url);
  if (url.origin !== self.location.origin) return;
  if (req.mode === 'navigate') {
    e.respondWith(navigationResponse(req, url));
    return;
  }
  e.respondWith(
    caches.match(req, { ignoreSearch: true }).then(
      (hit) =>
        hit ||
        fetch(req).then((res) => {
          if (res.ok) caches.open(CACHE).then((c) => c.put(req, res.clone()));
          return res;
        }),
    ),
  );
});
`;
writeFileSync(join(dist, 'sw.js'), sw);

const bytes = files.reduce((n, f) => n + statSync(join(dist, f)).size, 0);
console.log(`\nservice worker written: ${files.length} files, ${(bytes / 1048576).toFixed(1)} MB precached, version ${version}`);
